select id,
       left(case when char_length(trim(coalesce(raw_user_meta_data ->> 'name', ''))) >= 2
            then trim(raw_user_meta_data ->> 'name')
            else coalesce(nullif(split_part(email, '@', 1), ''), 'Ученик') end, 60),
       case when upper(coalesce(raw_user_meta_data ->> 'level', 'A0')) in ('A0','A1','A2','B1','B2','C1')
