-- English Tutor: production-ready learning schema and starter content.
-- Passwords remain exclusively in Supabase Auth (auth.users).

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

drop table if exists public.user_vocabulary cascade;
drop table if exists public.user_progress cascade;
drop table if exists public.lesson_exercises cascade;
drop table if exists public.vocabulary cascade;
drop table if exists public.users cascade;
drop table if exists public.profiles cascade;
drop table if exists public.lessons cascade;
drop table if exists public.english_levels cascade;

create table public.english_levels (
  code text primary key check (code in ('A0', 'A1', 'A2', 'B1', 'B2', 'C1')),
  title text not null,
  description text not null,
  vocabulary_goal integer not null check (vocabulary_goal > 0),
  order_index integer not null unique
);

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null check (char_length(display_name) between 2 and 60),
  level_code text not null default 'A0' references public.english_levels(code),
  total_xp integer not null default 0 check (total_xp >= 0),
  streak_days integer not null default 0 check (streak_days >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.lessons (
  id bigint generated by default as identity primary key,
  level_code text not null references public.english_levels(code) on update cascade,
  order_index integer not null,
  title text not null,
  subtitle text not null,
  theory text not null,
  rule_text text not null,
  examples jsonb not null default '[]'::jsonb check (jsonb_typeof(examples) = 'array'),
  xp integer not null default 50 check (xp > 0),
  estimated_minutes integer not null default 8 check (estimated_minutes > 0),
  source_url text not null,
  unique (level_code, order_index)
);

create table public.lesson_exercises (
  id bigint generated by default as identity primary key,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  order_index integer not null,
  exercise_type text not null default 'multiple_choice' check (exercise_type in ('multiple_choice')),
  prompt text not null,
  question text not null,
  options jsonb not null check (jsonb_typeof(options) = 'array' and jsonb_array_length(options) >= 2),
  correct_index integer not null check (correct_index >= 0),
  explanation text not null,
  unique (lesson_id, order_index)
);

create table public.vocabulary (
  id bigint generated by default as identity primary key,
  level_code text not null references public.english_levels(code) on update cascade,
  word text not null,
  transcription text not null default '',
  translation text not null,
  example text not null,
  source_url text not null,
  unique (level_code, word)
);

create table public.user_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  lesson_id bigint not null references public.lessons(id) on delete cascade,
  status text not null default 'in_progress' check (status in ('in_progress', 'completed')),
  correct_answers integer not null default 0 check (correct_answers >= 0),
  total_answers integer not null default 0 check (total_answers >= 0),
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, lesson_id),
  check (correct_answers <= total_answers)
);

create table public.user_vocabulary (
  user_id uuid not null references auth.users(id) on delete cascade,
  vocabulary_id bigint not null references public.vocabulary(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (user_id, vocabulary_id)
);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at before update on public.profiles
for each row execute function private.set_updated_at();
create trigger progress_set_updated_at before update on public.user_progress
for each row execute function private.set_updated_at();

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  requested_level text;
  requested_name text;
begin
  requested_level := upper(coalesce(new.raw_user_meta_data ->> 'level', 'A0'));
  if requested_level not in ('A0', 'A1', 'A2', 'B1', 'B2', 'C1') then
    requested_level := 'A0';
  end if;
  requested_name := trim(coalesce(new.raw_user_meta_data ->> 'name', split_part(coalesce(new.email, 'Ученик'), '@', 1)));
  if char_length(requested_name) < 2 then requested_name := 'Ученик'; end if;
  insert into public.profiles (id, display_name, level_code)
  values (new.id, left(requested_name, 60), requested_level)
  on conflict (id) do nothing;
  return new;
end;
$$;
revoke all on function private.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

